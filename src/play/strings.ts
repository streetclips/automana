const STRINGS: Record<Locale, typeof EN> = { en: EN, es: ES };

export function ui(): typeof EN {
  return STRINGS[getLocale()];
}

export function say(text: string, nemesis: boolean): string {
  const phrases = ui().log;
  for (const [key, re] of Object.entries(LOG) as [keyof typeof LOG, RegExp][]) {
    const m = re.exec(text);
    if (m) return phrases[key](m, nemesis);
  }
  return text[0].toUpperCase() + text.slice(1);
}
