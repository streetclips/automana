function attackers(list: string, name: (n: string) => string, blockedBy: (b: string) => string): string {
  return list.split(", ").map((part) => {
    const [, a, b] = /^(.+?)(?: \(blocked by (.+)\))?$/.exec(part)!;
    return `${name(a)}${b ? ` (${blockedBy(name(b))})` : ""}`;
  }).join(", ");
}

function names(list: string, name: (n: string) => string, nothing: string): string {
  return list === "nothing" ? nothing : list.split(", ").map(name).join(", ");
}

